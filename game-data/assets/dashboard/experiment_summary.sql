/* @bruin
name: dashboard.experiment_summary
type: bq.sql
description: >
  Gold layer summary table for A/B test analysis.
  Computes per-variant engagement and monetization metrics (ARPU, ARPPU, conversion rate,
  retention) from the player feature store, then calculates the absolute delta between
  the treatment and control groups to quantify experiment lift.
  Designed for "zero-SQL" consumption by BI tools and business stakeholders.

materialization:
    type: table
    strategy: create+replace

depends:
  - python_analytics.player_features

columns:
  - name: experiment_id
    type: string
    description: Unique identifier of the A/B experiment
  - name: variant
    type: string
    description: "Experiment variant: 'control', 'treatment', or 'absolute_delta' (lift row)"
    checks:
      # Only check unique to this Gold layer: upstream layers already guarantee not_null on player_id,
      # variant, revenue (non_negative), days_active (positive) and install_date (not_null).
      # Here we only validate that no unexpected variant label slips through the aggregation.
      - name: accepted_values
        value: ["control", "treatment", "absolute_delta"]
  - name: total_players
    type: integer
    description: Total number of players in this variant
  - name: avg_days_active
    type: float
    description: Average number of unique active days per player
  - name: avg_sessions
    type: float
    description: Average number of session_start events per player
  - name: buyers
    type: integer
    description: Number of players who made at least one purchase
  - name: conversion_rate
    type: float
    description: Share of players who made a purchase (buyers / total_players)
  - name: total_revenue
    type: float
    description: Total gross revenue generated by this variant
  - name: arpu
    type: float
    description: Average Revenue Per User (total_revenue / total_players)
  - name: arppu
    type: float
    description: Average Revenue Per Paying User (total_revenue / buyers)
  - name: retention_rate
    type: float
    description: Share of players who were active on more than one day (days_active > 1)
@bruin */

-- ============================================================
-- STEP 1: Per-variant aggregated metrics
-- Source: python_analytics.player_features (Advanced Silver / Feature Store)
-- Each row = one variant (control / treatment) within an experiment
-- ============================================================
WITH metrics AS (
    SELECT
        experiment_id,
        variant,
        COUNT(*)                                                AS total_players,
        AVG(days_active)                                        AS avg_days_active,
        AVG(total_sessions)                                     AS avg_sessions,
        COUNTIF(has_purchase)                                   AS buyers,
        SAFE_DIVIDE(COUNTIF(has_purchase), COUNT(*))            AS conversion_rate,
        SUM(total_revenue)                                      AS total_revenue,
        SAFE_DIVIDE(SUM(total_revenue), COUNT(*))               AS arpu,
        SAFE_DIVIDE(SUM(total_revenue), COUNTIF(has_purchase))  AS arppu,
        SAFE_DIVIDE(COUNTIF(days_active > 1), COUNT(*))         AS retention_rate
    FROM python_analytics.player_features
    GROUP BY 1, 2
),

-- ============================================================
-- STEP 2: Absolute lift (delta) — treatment minus control
-- Produces a synthetic 'absolute_delta' row per experiment
-- showing the raw uplift across all key metrics.
-- SAFE_DIVIDE is used in step 1 to prevent division-by-zero
-- crashes on outlier or sparse data.
-- ============================================================
delta AS (
    SELECT
        t.experiment_id,
        'absolute_delta'                            AS variant,
        t.total_players    - c.total_players        AS total_players,
        t.avg_days_active  - c.avg_days_active      AS avg_days_active,
        t.avg_sessions     - c.avg_sessions         AS avg_sessions,
        t.buyers           - c.buyers               AS buyers,
        t.conversion_rate  - c.conversion_rate      AS conversion_rate,
        t.total_revenue    - c.total_revenue        AS total_revenue,
        t.arpu             - c.arpu                 AS arpu,
        t.arppu            - c.arppu                AS arppu,
        t.retention_rate   - c.retention_rate       AS retention_rate
    FROM metrics t
    -- Self-join: match each treatment row to its control counterpart
    JOIN metrics c
      ON  t.experiment_id = c.experiment_id
      AND c.variant = 'control'
    WHERE t.variant != 'control'
)

-- ============================================================
-- STEP 3: Final output — stack metrics + delta rows,
-- ordered for easy reading: control → treatment → delta
-- ============================================================
SELECT *
FROM (
    SELECT * FROM metrics
    UNION ALL
    SELECT * FROM delta
)
ORDER BY
    experiment_id,
    CASE variant
        WHEN 'control'        THEN 1
        WHEN 'treatment'      THEN 2
        WHEN 'absolute_delta' THEN 3
    END;
